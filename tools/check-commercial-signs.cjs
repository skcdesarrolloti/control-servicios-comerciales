/* Run against the local-only fixture: php -S 127.0.0.1:8771 -t . */
const assert = require('node:assert/strict');
const { chromium } = require(process.env.SCM_PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.env.SCM_BROWSER_CHANNEL || (process.platform === 'win32' ? 'msedge' : undefined) });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, permissions: ['geolocation'], geolocation: { latitude: 6.2, longitude: -75.5, accuracy: 8 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:8771/tests/Fixtures/commercial-signs.php');
    await page.locator('[data-sign-type="Nuevo"]').waitFor();
    assert.equal(await page.locator('[data-sign-type]').count(), 2);
    assert.equal(await page.locator('[data-sign-form]').isVisible(), false);
    await page.screenshot({ path: 'output/commercial-signs-desktop.png', fullPage: true });
    await page.locator('[data-commercial-dropdown-trigger="comerciales"]').click();
    const navigation = page.waitForResponse(response => response.request().postData()?.includes('commercial_tickets_filter'));
    await page.locator('[data-commercial-dropdown-menu="comerciales"] a[data-commercial-tab="anadir_aviso"]').click();
    await navigation;
    await page.locator('[data-sign-type="Nuevo"]').click();
    await page.locator('#csg-ticket').fill('100');
    await page.locator('#csg-property').fill('500');
    await page.locator('[data-sign-lookup]').click();
    await page.waitForFunction(() => document.querySelector('[data-sign-property-status]').textContent.includes('Inmueble #500'));
    assert.equal(await page.locator('#csg-ruta').inputValue(), '1');
    assert.equal(await page.locator('#csg-reference').inputValue(), 'Frente al parque');
    await page.locator('#csg-decoy').selectOption('No');
    await page.locator('#csg-promocionado_por').selectOption('Inmmobiliaria');
    assert.equal(await page.locator('[data-sign-competition]').isVisible(), true);
    await page.locator('#csg-competencia').selectOption('Inmobiliaria de prueba');
    const image = { name: 'evidence.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') };
    await page.locator('#csg-photos').setInputFiles([image, { ...image, name: 'evidence-2.png' }]);
    assert.equal(await page.locator('[data-sign-previews] img').count(), 2);
    await page.getByRole('button', { name: 'Quitar foto 2', exact: true }).click();
    assert.equal(await page.locator('[data-sign-previews] img').count(), 1);
    await page.locator('[data-sign-submit]').click();
    assert.match(await page.locator('[data-sign-error]').innerText(), /Captura la ubicación/);
    await page.locator('[data-sign-capture]').click();
    await page.waitForFunction(() => document.querySelector('[data-sign-location-status]').textContent.includes('Ubicación capturada'));
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: 'output/commercial-signs-new-form.png', fullPage: true });
    const form = await page.locator('[data-sign-form]').evaluate(node => Object.fromEntries([...new FormData(node).entries()].filter(([, value]) => typeof value === 'string')));
    // These select fields use array names in the browser; this retry intentionally leaves them empty.
    delete form['promocionado_por[]']; delete form['competencia[]'];
    let responsePromise = page.waitForResponse(response => response.request().method() === 'POST' && response.url().includes('/tests/Fixtures/commercial-signs.php'));
    await page.locator('[data-sign-submit]').click();
    let response = await responsePromise;
    let result = await response.json();
    assert.equal(result.success, true, JSON.stringify(result));
    assert.equal(result.data.portal_pending, false);
    await page.locator('[data-sign-result]').waitFor({ state: 'visible' });
    const retry = await context.request.post('http://127.0.0.1:8771/tests/Fixtures/commercial-signs.php', { form: { ...form, nonce: 'fixture', action: 'commercial_sign_save' } });
    const retryResult = await retry.json();
    assert.equal(retryResult.data.id_aviso, result.data.id_aviso);
    const unauthorized = await context.request.post('http://127.0.0.1:8771/tests/Fixtures/commercial-signs.php', { form: { action: 'commercial_sign_lookup', nonce: 'fixture', id_ticket: '200', id_inmueble: '600' } });
    assert.equal(unauthorized.status(), 403);
    const invalidCsrf = await context.request.post('http://127.0.0.1:8771/tests/Fixtures/commercial-signs.php', { form: { action: 'commercial_sign_lookup', nonce: 'invalid', id_ticket: '100', id_inmueble: '500' } });
    assert.equal(invalidCsrf.status(), 403);
    await page.locator('[data-sign-again]').click();
    await page.locator('[data-sign-type="Nuevo"]').click();
    const nextToken = await page.locator('[name=request_id]').inputValue();
    assert.notEqual(nextToken, form.request_id);
    await page.locator('[data-sign-back]').click();
    await page.locator('[data-sign-type="Retoque"]').click();
    assert.equal(await page.locator('[name=request_id]').inputValue(), nextToken);
    await page.locator('#csg-ticket').fill('100');
    await page.locator('#csg-property').fill('500');
    await page.locator('[data-sign-lookup]').click();
    await page.waitForFunction(() => document.querySelector('[data-sign-property-status]').textContent.includes('Inmueble #500'));
    assert.equal(await page.locator('#csg-tipo_inmueble').isDisabled(), true);
    await page.locator('#csg-pego').selectOption('No');
    await page.locator('#csg-razon').selectOption('Arrendado');
    await page.locator('#csg-decoy').selectOption('No');
    assert.equal(await page.locator('#csg-quantity').inputValue(), '0');
    assert.equal(await page.locator('[data-sign-unpublish]').isVisible(), true);
    await page.locator('#csg-photos').setInputFiles(image);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: 'output/commercial-signs-mobile.png', fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.locator('[data-sign-capture]').click();
    await page.waitForFunction(() => document.querySelector('[data-sign-location-status]').textContent.includes('Ubicación capturada'));
    // Changing the property clears the GPS and invalidates the lookup.
    await page.locator('#csg-property').fill('600');
    assert.equal(await page.locator('[name=mapa_latitud]').inputValue(), '');
    await page.locator('#csg-property').fill('500');
    await page.locator('[data-sign-lookup]').click();
    await page.waitForFunction(() => document.querySelector('[data-sign-property-status]').textContent.includes('Inmueble #500'));
    await page.locator('[data-sign-capture]').click();
    await page.waitForFunction(() => document.querySelector('[data-sign-location-status]').textContent.includes('Ubicación capturada'));
    responsePromise = page.waitForResponse(response => response.request().method() === 'POST' && response.url().includes('/tests/Fixtures/commercial-signs.php'));
    await page.locator('[data-sign-submit]').click();
    response = await responsePromise; result = await response.json();
    assert.equal(result.success, true, JSON.stringify(result));
    assert.equal(result.data.portal_pending, true);
    await page.locator('[data-sign-result] .csg-warning').waitFor({ state: 'visible' });
    const syncResponse = page.waitForResponse(response => response.request().method() === 'POST' && response.url().includes('/tests/Fixtures/commercial-signs.php'));
    await page.locator('[data-sign-retry]').click();
    assert.equal((await (await syncResponse).json()).data.portal_pending, true);
    assert.deepEqual(errors, []);
    console.log('Commercial signs browser checks: OK (selection, AJAX navigation, lookup, evidence, GPS, new sign, retouch, retries, permissions and mobile layout).');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
