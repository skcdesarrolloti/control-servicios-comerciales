const assert = require('node:assert/strict');
const {chromium} = require(process.env.SCM_PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const browser = await chromium.launch({headless:true,channel:process.env.SCM_BROWSER_CHANNEL || (process.platform === 'win32' ? 'msedge' : undefined)});
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1050},permissions:['geolocation'],geolocation:{latitude:6.2,longitude:-75.5,accuracy:8}});
    const page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const api = 'http://127.0.0.1:8771/tests/Fixtures/commercial-property-entry.php';
    await page.goto(api);
    await page.locator('[data-commercial-open-case="100"]').click();
    await page.locator('[data-commercial-task-form="sign"]').click();
    const sign = page.locator('#commercial-case-modal [data-commercial-signs]');
    await page.waitForFunction(() => document.querySelector('#commercial-case-modal [data-sign-form]')?._lookupKey);
    assert.equal(await sign.locator('[name=id_ticket]').inputValue(),'100');
    await sign.locator('[data-commercial-return-case]').click();
    await page.route('**/tests/Fixtures/commercial-property-entry.php', route => route.fulfill({status:422,contentType:'application/json',body:JSON.stringify({success:false,data:{message:'Mensaje de validación de prueba.'}})}),{times:1});
    await page.locator('[data-commercial-task-form="property"]').click();
    await page.getByRole('alert').filter({hasText:'Mensaje de validación de prueba.'}).waitFor();
    await page.getByRole('button',{name:'Reintentar',exact:true}).click();
    const root = page.locator('[data-commercial-property-entry]'), media = root.locator('[data-media-embedded]');
    await root.waitFor();
    assert.equal(await root.locator('[name=id_ticket]').inputValue(),'100');
    await root.locator('[name=tipo_captacion]').selectOption('Recaptacion');
    assert.equal(await root.locator('[data-property-field=codigo_anterior]').isVisible(),true);
    await root.locator('[name=tipo_captacion]').selectOption('Nueva');
    await page.screenshot({path:'output/property-entry-desktop.png'});
    async function tab(index) { await root.locator('[data-entry-tab="' + index + '"]').click(); }
    async function fillField(name, value) {
      const field = root.locator('[name="' + name + '"]');
      const panel = await field.evaluate(node => node.closest('[data-entry-panel]').dataset.entryPanel);
      await tab(panel);
      await field.evaluate(node => { const section = node.closest('details'); if (section) section.open = true; });
      const choice = root.locator('[data-choice-group="' + name + '"] [data-choice-value="' + value + '"]');
      if (await choice.count()) await choice.click();
      else if (await field.evaluate(node => node.tagName === 'SELECT')) await field.selectOption(value);
      else await field.fill(value);
    }
    async function fillRequired() {
      const fields = {tipo_captacion:'Nueva',id_propietario:'10',titulo:'Casa registrada desde la tarea',descripcion:'Registro de prueba aislado.',tipo_oferta:'117',tipo_inmueble:'106',destinacion:'121',pertenece_regimen:'No',area_construida:'100',area_terreno:'120',tiene_parqueadero:'No',tiene_deposito:'No',tiene_vigilancia:'No',habitaciones:'2',banos:'1',precio_arriendo:'1500000',antiguedad_inmueble:'1 a 8 años',ano_construccion:'2020',avaluo_catastral:'100000000',referencia_catastral:'CAT123',estrato:'3',procedencia:'Internet',amoblado:'No',desea_aviso:'Si',pais:'Colombia',departamento:'Antioquia',ciudad:'Medellín',barrio:'El Poblado',direccion_completa:'Calle 10 #20-30',punto_referencia:'Frente al parque',direccion_fisica:'Calle 10 #20-30',tiene_rnt:'No'};
      for (const [name,value] of Object.entries(fields)) await fillField(name,value);
    }
    await fillRequired();
    assert.equal(await root.locator('[name=ruta]').inputValue(),'1');
    await fillField('tipo_oferta','119');
    assert.equal(await root.locator('[name=precio_venta]').isEnabled(),true);
    await fillField('tipo_oferta','118');
    await fillField('precio_venta','250000000');
    await fillField('acepta_permuta','No');
    await tab(3);
    await root.locator('[data-neighborhood-status]').filter({hasText:'basadas en'}).waitFor();
    const interior = root.locator('[data-choice-group=interiores]');
    assert.equal(await interior.locator('[data-choice-value=Sala]').getAttribute('aria-pressed'),'false');
    await interior.locator('[data-apply-suggestions]').click();
    assert.equal(await interior.locator('[data-choice-value=Sala]').getAttribute('aria-pressed'),'true');
    assert.ok((await interior.locator('[data-choice-value=Sala] i').first().getAttribute('class')).includes('fa-couch'));
    await interior.locator('[data-feature-search]').fill('cocina');
    assert.equal(await interior.locator('[data-choice-value=Sala]').isVisible(),false);
    await interior.locator('[data-feature-search]').fill('');
    await page.screenshot({path:'output/property-features-desktop.png'});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'output/property-features-mobile.png'});
    assert.equal(await root.evaluate(node => node.scrollWidth > node.clientWidth + 1),false);
    await page.setViewportSize({width:1440,height:1050});
    await tab(4);
    const photoData = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 2400; canvas.height = 1600; const ctx = canvas.getContext('2d'); const gradient = ctx.createLinearGradient(0,0,2400,1600); gradient.addColorStop(0,'#254c78'); gradient.addColorStop(1,'#bbcce0'); ctx.fillStyle=gradient; ctx.fillRect(0,0,2400,1600); return canvas.toDataURL('image/jpeg').split(',')[1]; });
    const photo = {name:'interior-grande.jpg',mimeType:'image/jpeg',buffer:Buffer.from(photoData,'base64')};
    async function addPhotos() {
      while (await media.locator('[data-media-gallery] img').count()) await media.getByRole('button',{name:/^Quitar foto /}).first().click();
      await media.locator('[data-media-input=cover]').setInputFiles(photo);
      await media.locator('[data-media-cover] img').waitFor();
      await page.waitForFunction(() => document.querySelector('[data-media-embedded]')?._media.portada?.file && !document.querySelector('[data-media-embedded]')._busy);
      await media.locator('[data-media-input=gallery]').setInputFiles([photo,{...photo,name:'segunda.jpg'}]);
      await page.waitForFunction(() => document.querySelector('[data-media-embedded]')?._media.galeria.length === 2 && !document.querySelector('[data-media-embedded]')._busy);
    }
    await addPhotos();
    await media.locator('[data-media-cover]').getByRole('button',{name:'Editar',exact:true}).click();
    const editor = page.locator('dialog.cpm-editor');
    await editor.waitFor();
    await page.waitForFunction(() => document.querySelector('.cpm-editor-status')?.textContent.includes('px'));
    assert.equal(await editor.locator('[data-edit=save]').evaluate(node => getComputedStyle(node).backgroundColor),'rgb(16, 46, 88)');
    await editor.locator('[data-setting=ratio]').uncheck();
    await editor.locator('[data-setting=width]').fill('1200'); await editor.locator('[data-setting=height]').fill('800');
    await editor.locator('[data-edit=size]').click();
    await editor.locator('[data-edit=undo]').click();
    await page.waitForFunction(() => document.querySelector('[data-setting=width]')?.value === '1700');
    await editor.locator('[data-setting=text]').fill('Vista interior');
    await editor.locator('[data-edit=text-add]').click();
    await editor.locator('[data-edit=rect]').click();
    await editor.locator('[data-edit=undo]').click();
    await editor.locator('[data-setting=brightness]').fill('12');
    await page.screenshot({path:'output/property-photo-editor.png'});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await editor.evaluate(node => node.scrollWidth > node.clientWidth + 1),false);
    await page.screenshot({path:'output/property-photo-editor-mobile.png'});
    await page.setViewportSize({width:1440,height:1050});
    await editor.locator('[data-edit=save]').click();
    await editor.waitFor({state:'detached'});
    await media.locator('[data-media-gallery]').getByRole('button',{name:'Mover foto 2 antes',exact:true}).click();
    await media.locator('[name=video_del_inmueble]').fill('https://youtu.be/abcdefghijk');
    await page.screenshot({path:'output/property-media-inline.png'});
    const denied = await context.request.post(api,{form:{action:'commercial_property_entry_form',nonce:'fixture',ticket_pk:'200'}});
    assert.equal(denied.status(),403);
    let rejectOnce = true, entries = 0;
    page.on('request', request => { if (request.method() === 'POST' && request.postData()?.includes('commercial_property_entry_save')) entries++; });
    const failMedia = async route => { if (rejectOnce && route.request().postData()?.includes('commercial_property_media_save')) { rejectOnce=false; await route.fulfill({status:422,contentType:'application/json',body:JSON.stringify({success:false,data:{message:'Fallo de multimedia de prueba.'}})}); } else await route.continue(); };
    await page.route('**/tests/Fixtures/commercial-property-entry.php',failMedia);
    await root.locator('[data-property-submit]').click();
    await root.locator('[data-property-error]').filter({hasText:'ya tiene sus datos guardados'}).waitFor();
    const code = await root.evaluate(node => node.querySelector('form')._propertySaved.id_inmueble);
    await page.unroute('**/tests/Fixtures/commercial-property-entry.php',failMedia);
    await root.locator('[data-property-submit]').click();
    await root.locator('[data-property-result]').waitFor({state:'visible'});
    assert.equal(entries,1,'Reintentar multimedia debe conservar el inmueble existente.');
    await root.locator('[data-property-result] [data-commercial-return-case]').click();
    await page.locator('[data-commercial-task-form=media]').click();
    const standalone = page.locator('[data-commercial-property-media]');
    await standalone.waitFor();
    assert.equal(await standalone.evaluate(node => node._media.id_inmueble),code);
    assert.equal(await standalone.locator('[data-media-gallery] img').count(),2);
    await standalone.locator('[data-commercial-return-case]').click();
    await page.locator('[data-commercial-task-form=property]').click();
    await root.waitFor();
    await root.locator('[name=modo_ingreso]').selectOption('adelantado');
    await root.locator('[name=codigo_adelantado]').fill('800');
    await fillRequired(); await fillField('presenta-aviso','No'); await tab(4);
    await addPhotos();
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'output/property-entry-mobile.png'});
    assert.equal(await root.evaluate(node => node.scrollWidth > node.clientWidth + 1),false);
    await root.locator('[data-property-submit]').click();
    await root.locator('[data-property-result]').waitFor({state:'visible'});
    assert.equal(await root.evaluate(node => node.querySelector('form')._propertySaved.id_inmueble),800);
    assert.deepEqual(errors,[]);
    console.log('Property entry: OK (inline media/editor, icon cards, neighborhood suggestions, search, single save, retry without duplicates, reserved code, permissions, mobile and 422 feedback).');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
