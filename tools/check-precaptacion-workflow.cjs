const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { chromium } = require(process.argv[2] ? path.join(process.argv[2], 'playwright') : 'playwright');

(async () => {
  const browser = await chromium.launch({headless:true,channel:'msedge'});
  const endpoint = 'http://127.0.0.1:8770/tests/Fixtures/precaptacion.php';
  const errors = [];
  fs.mkdirSync('output',{recursive:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/public/precaptacion-api.php', route => route.continue({url:endpoint}));
    await page.goto(endpoint);
    const nonce = await page.locator('body').getAttribute('data-precap-nonce');
    const post = async (action, extra = {}) => {
      const response = await page.request.post(endpoint,{form:{action,nonce,id_precaptacion:'1',...extra}});
      const payload = await response.json();
      return {status:response.status(),payload};
    };
    const inspect = async () => (await page.request.get(endpoint+'?inspect=1')).json();
    const call = {tipo_gestion:'llamada',resultado_contacto:'no_contesto',merece_ticket:'Seguir llamando',resultado:'No contestó',proximo_contacto:new Date(Date.now()+86400000).toISOString().slice(0,16)};
    for (let i=0;i<2;i++) assert.equal((await post('precaptaciones_actualizar',call)).status,200);
    assert.equal((await post('precaptaciones_actualizar',{tipo_gestion:'administrativa',resultado_contacto:'por_llamar',merece_ticket:'No',resultado:'Corrigió el contacto'})).status,200);
    assert.equal(Number((await inspect()).process.unanswered),2);
    await page.reload();
    await page.locator('[data-precaptaciones-row-id="1"] .precaptaciones__editar').click();
    const edit = page.locator('#precaptaciones-precap-modal-1');
    await edit.locator('[name="resultado_contacto"]').selectOption('no_contesto');
    await edit.locator('[name="resultado"]').fill('Tercer intento sin respuesta');
    assert.ok(await edit.locator('[name="proximo_contacto"]').isDisabled());
    const saved = page.waitForResponse(r => r.request().postData()?.includes('precaptaciones_actualizar'));
    await edit.locator('[type="submit"]').click();
    assert.equal((await saved).status(),200);
    await page.locator('[data-precap-notice-confirm]').click();
    await edit.waitFor({state:'hidden'});
    await page.waitForFunction(() => !document.querySelector('[data-precaptaciones-panel]').classList.contains('is-loading'));
    assert.equal(await page.locator('[data-precaptaciones-row-id="1"] .precaptaciones__editar').count(),0);
    let data = await inspect();
    assert.equal(data.process.status,'cerrada');
    assert.equal(Number(data.process.attempts),3);
    assert.equal(data.history.length,4);
    assert.equal((await post('precaptaciones_actualizar',call)).status,422);
    assert.equal((await post('precaptaciones_reabrir',{motivo:'Nuevo teléfono'})).status,403);

    await page.goto(endpoint+'?admin=1');
    await page.locator('[data-precaptaciones-row-id="1"] .precaptaciones__detalle').click();
    const detail = page.locator('#precaptaciones-detalle-modal-1');
    assert.ok((await detail.innerText()).includes('3 intentos agotados'));
    await page.screenshot({path:'output/precaptacion-closed-workflow.png'});
    const reopen = detail.locator('[data-precap-process-form]').filter({has:page.locator('[name="action"][value="precaptaciones_reabrir"]')});
    await reopen.locator('[name="motivo"]').fill('Nuevo teléfono confirmado');
    await reopen.locator('[type="submit"]').click();
    await page.locator('[data-precap-notice-confirm]').click();
    await detail.waitFor({state:'hidden'});
    await page.waitForFunction(() => !document.querySelector('[data-precaptaciones-panel]').classList.contains('is-loading'));
    data = await inspect();
    assert.equal(Number(data.process.cycle),2);
    assert.equal(Number(data.process.unanswered),0);
    await page.locator('[data-precaptaciones-row-id="1"] .precaptaciones__detalle').click();
    const assign = detail.locator('[data-precap-process-form]').filter({has:page.locator('[name="action"][value="precaptaciones_asignar"]')});
    await assign.locator('[name="responsable"]').selectOption('202');
    await assign.locator('[name="motivo"]').fill('Reparto comercial');
    await assign.locator('[type="submit"]').click();
    await page.locator('[data-precap-notice-confirm]').click();
    await detail.waitFor({state:'hidden'});
    await page.goto(endpoint+'?admin=0&employee=101');
    assert.equal(await page.locator('[data-precaptaciones-row-id="1"]').count(),0);
    assert.equal((await post('precaptaciones_actualizar',call)).status,403);
    await page.goto(endpoint+'?admin=0&employee=202');
    assert.equal((await post('precaptaciones_actualizar',{...call,resultado_contacto:'contactado',merece_ticket:'Si',resultado:'Propietario confirma interés'})).status,200);
    await page.reload();
    await page.locator('[data-precaptaciones-row-id="1"]').getByRole('button',{name:'Crear tarea',exact:true}).click();
    assert.ok(await page.locator('#precaptaciones-ticket-modal-1').isVisible());
    assert.equal(await page.locator('#precaptaciones-ticket-modal-1 [name="asignado"]').inputValue(),'202');
    await page.getByRole('button',{name:'Continuar después',exact:true}).click();
    await page.locator('#precaptaciones-ticket-modal-1').waitFor({state:'hidden'});
    await page.locator('[data-precaptaciones-row-id="1"]').getByRole('button',{name:'Crear tarea',exact:true}).click();
    const task = await post('precaptaciones_crear_ticket',{asignado:'202',medio:'Manipulado',solicitante:'Manipulado',asunto:'Captación confirmada',descripcion:'Visita acordada'});
    assert.equal(task.status,200,JSON.stringify(task.payload));
    data = await inspect();
    assert.equal(data.row.id_empleado,'101','El captador permanece separado del responsable de llamadas');
    assert.equal(data.task.medio,'Recorrido','Conserva el medio original');
    assert.equal(data.task.solicitante,'Contacto de prueba');
    assert.equal(data.process.status,'convertida');
    assert.equal(Number(data.process.attempts),1,'Crear una tarea pendiente no registra otra llamada');
    assert.equal(Number((await post('precaptaciones_crear_ticket',{asignado:'202',asunto:'Otra',descripcion:'Otra'})).payload.data.ticket_id),Number(task.payload.data.ticket_id));

    const home = await browser.newPage({viewport:{width:1440,height:1000}});
    home.on('pageerror', error => errors.push(error.message));
    await home.goto(endpoint+'?admin=1&home=1&seed_home=1');
    const modal = home.locator('[data-commercial-advisory-modal="precaptaciones"]');
    await modal.waitFor({state:'visible'});
    assert.ok((await home.locator('[data-precap-home]').innerText()).toLowerCase().includes('total global del equipo'));
    assert.ok((await home.locator('[data-precap-home]').innerText()).includes('Ver pendientes (2)'));
    await modal.locator('summary').click();
    assert.ok((await modal.innerText()).includes('Segundo consultor'));
    await home.screenshot({path:'output/precaptacion-home-admin-popup.png'});
    await modal.locator('[data-commercial-close-advisory]').first().click();
    await modal.waitFor({state:'hidden'});
    await home.screenshot({path:'output/precaptacion-home-admin.png'});
    assert.ok((await home.locator('[data-precap-home] a').first().getAttribute('href')).includes('precaptaciones_estado_contacto=por_llamar'));
    await home.goto(endpoint+'?admin=0&employee=101&home=1');
    assert.ok((await home.locator('[data-precap-home]').innerText()).toLowerCase().includes('mis registros asignados'));
    assert.ok((await home.locator('[data-precap-home]').innerText()).includes('Ver pendientes (1)'));
    await home.locator('[data-commercial-open-advisory]').click();
    assert.ok(!(await modal.innerText()).includes('Registro de otro funcionario'));
    await home.setViewportSize({width:390,height:844});
    await home.screenshot({path:'output/precaptacion-home-mobile-popup.png'});
    assert.ok(await home.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    const bounds = await modal.locator('footer').boundingBox();
    assert.ok(bounds.y >= 0 && bounds.y + bounds.height <= 844);
    await modal.locator('[data-commercial-close-advisory]').first().click();
    await home.goto(endpoint+'?admin=0&employee=202&home=1');
    assert.ok((await home.locator('[data-precap-home]').innerText()).includes('Ver pendientes (1)'));
    await home.locator('[data-commercial-open-advisory]').click();
    assert.ok(!(await modal.innerText()).includes('Contacto de prueba'));
    assert.equal(await modal.locator('summary').count(),0,'El desglose global es exclusivo del administrador');
    assert.deepEqual(errors,[]);
    console.log('OK: 3 intentos, edición administrativa, cierre/reapertura, asignación y permisos, tarea sin llamada adicional, medio original, Inicio personal/global y popup móvil.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
