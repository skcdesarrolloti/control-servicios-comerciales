// Generar las vistas --audit y --audit --admin y servir el repositorio en 127.0.0.1:8769.
const path = require('path');
const fs = require('fs');
const assert = require('node:assert/strict');
const { chromium } = require(process.argv[2] ? path.join(process.argv[2], 'playwright') : 'playwright');
let browser;
(async () => {
  browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = 'http://127.0.0.1:8769';
  const api = (action, extra = {}, admin = false) => page.request.post(base + '/tests/Fixtures/notifications-api.php?audit=' + (admin ? 'admin' : 'user'), { form: { action, nonce: 'fixture', ...extra } });
  for (const action of ['commercial_notifications_detail', 'commercial_notifications_delete', 'commercial_notifications_report']) {
    assert.equal((await api(action, { id: '1', nonce: 'bad' }, true)).status(), 403, 'Se admite un nonce inválido');
    assert.equal((await api(action, { id: '1', restricted: '1' })).status(), 403, 'Se admite una vista sin permiso');
  }
  assert.equal((await api('commercial_notifications_delete', { id: '1' })).status(), 403);
  assert.equal((await api('commercial_notifications_delete', { id: '4' }, true)).status(), 409);
  for (const id of ['5', '6', '7', '8', '999']) assert.equal((await api('commercial_notifications_detail', { id })).status(), 404, 'La vista previa expone datos ajenos');
  for (const id of ['7', '8']) assert.equal((await api('commercial_notifications_delete', { id }, true)).status(), 409, 'Se elimina otro proyecto/módulo');
  assert.equal((await api('commercial_notifications_report', { date_from: '2026-02-30' }, true)).status(), 422);
  assert.equal((await (await api('commercial_notifications_report', { employee_id: '901' })).json()).data.totals.total, 0);

  await page.goto(base + '/output/notifications-audit-user.html');
  await page.locator('[data-notif-view="queue"]').click();
  await page.locator('[data-notif-history-id="1"]').waitFor();
  assert.equal(await page.locator('[data-notif-queue-rows] tr').count(), 4);
  assert.equal(await page.locator('[data-notif-delete-id]').count(), 0);
  await page.locator('[data-notif-history-id="1"]').click();
  await page.locator('[data-notif-history-content]:visible').waitFor();
  assert.match(await page.locator('[data-notif-history-info]').innerText(), /Ana Pérez.*ID 900/s);
  assert.equal(await page.locator('[data-notif-history-email]').getAttribute('sandbox'), '');
  await page.frameLocator('[data-notif-history-email]').getByText('Mensaje de prueba para el informe', { exact: false }).waitFor();
  await page.screenshot({ path: 'output/notifications-history-email.png', fullPage: true });
  await page.locator('[data-notif-history-close]').click();
  await page.locator('[data-notif-history-id="2"]').click();
  await page.locator('[data-notif-history-content]:visible').waitFor();
  assert.match(await page.locator('[data-notif-history-text]').innerText(), /SKC SuCasa Inmobiliaria Mensaje de prueba/);
  await page.locator('[data-notif-history-close]').click();
  await page.locator('[data-notif-view="queue"]').focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('[data-notif-view="report"]').getAttribute('aria-selected'), 'true');
  await page.locator('[data-notif-report-summary]').filter({ hasText: '4 mensajes creados' }).waitFor();

  await page.goto(base + '/output/notifications-audit-admin.html');
  await page.locator('[data-notif-view="queue"]').click();
  await page.locator('[data-notif-delete-id="2"]').waitFor();
  assert.equal(await page.locator('[data-notif-queue-rows] tr').count(), 6);
  assert.equal(await page.locator('[data-notif-delete-id="4"]').isDisabled(), true);
  assert.match(await page.locator('[data-notif-queue-rows]').innerText(), /Otro usuario/);
  await page.screenshot({ path: 'output/notifications-audit-queue.png', fullPage: true });
  await page.locator('[data-notif-delete-id="2"]').click();
  await page.locator('[data-notif-delete-cancel]').click();
  assert.equal(await page.locator('[data-notif-delete-modal]').isVisible(), false);
  await page.locator('[data-notif-delete-id="2"]').click();
  await page.locator('[data-notif-delete-confirm]').click();
  await page.locator('[data-notif-feedback]').filter({ hasText: 'Notificación eliminada' }).waitFor();
  assert.equal(await page.locator('[data-notif-delete-modal]').isVisible(), false);
  await page.locator('[data-notif-history-id="6"]').click();
  await page.locator('[data-notif-history-content]:visible').waitFor();
  assert.match(await page.locator('[data-notif-history-info]').innerText(), /Sin autor registrado/);
  await page.locator('[data-notif-history-close]').click();
  await page.locator('[data-notif-view="report"]').click();
  await page.locator('[data-notif-report-summary]').filter({ hasText: '6 mensajes creados' }).waitFor();
  assert.equal(await page.locator('[data-notif-report-rows] tr').count(), 5);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('[data-notif-report-export]').click();
  const download = await downloadPromise;
  await download.saveAs('output/notifications-report.csv');
  const csv = fs.readFileSync('output/notifications-report.csv', 'utf8');
  assert.match(csv, /Ana Pérez/);
  assert.match(csv, /Otro usuario/);
  assert.match(csv, /Sin autor registrado/);
  assert.match(csv, /Última creación \(Colombia\)/);
  await page.screenshot({ path: 'output/notifications-audit-report.png', fullPage: true });
  await page.locator('[data-notif-report-form] [name="employee_id"]').fill('901');
  await page.locator('[data-notif-report-form] button[type="submit"]').click();
  await page.locator('[data-notif-report-summary]').filter({ hasText: '1 mensajes creados' }).waitFor();
  assert.equal(await page.locator('[data-notif-report-rows] tr').count(), 1);
  await page.locator('[data-notif-report-form] [name="employee_id"]').fill('');
  await page.locator('[data-notif-report-form] [name="date_from"]').fill('2026-10-09');
  await page.locator('[data-notif-report-form] button[type="submit"]').click();
  await page.locator('[data-notif-report-rows]').getByText('No hay mensajes para estos filtros.').waitFor();
  assert.equal(await page.locator('[data-notif-report-export]').isDisabled(), true);
  await page.locator('[data-notif-report-form] [name="date_from"]').fill('');
  await page.locator('[data-notif-report-form] button[type="submit"]').click();
  await page.locator('[data-notif-report-summary]').filter({ hasText: '6 mensajes creados' }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.locator('[data-commercial-notifications]').evaluate(node => node.scrollWidth > node.clientWidth), false, 'El informe desborda el panel móvil');
  await page.screenshot({ path: 'output/notifications-audit-report-mobile.png', fullPage: true });
  await page.locator('[data-notif-view="queue"]').click();
  await page.locator('[data-notif-history-id="3"]').click();
  await page.locator('[data-notif-history-content]:visible').waitFor();
  await page.screenshot({ path: 'output/notifications-history-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Historial, autoría, vista previa, permiso administrativo, eliminación, informe/CSV, CSRF y móvil: OK');
  await browser.close();
})().catch(async error => { console.error(error); if (browser) await browser.close(); process.exit(1); });
