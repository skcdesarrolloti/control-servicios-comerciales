const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { chromium } = require(process.argv[2] ? path.join(process.argv[2], 'playwright') : 'playwright');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const endpoint = 'http://127.0.0.1:8770/tests/Fixtures/precaptacion.php';
    await page.route('**/public/precaptacion-api.php', route => route.continue({ url: endpoint }));
    await page.route('**/public/file.php?*', route => route.fulfill({status:200,contentType:'image/png',body:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jWZkAAAAASUVORK5CYII=', 'base64')}));
    await page.goto(endpoint);
    await page.locator('[data-precaptaciones-panel]').waitFor();
    await page.getByRole('button', { name: 'Registrar precaptación', exact: true }).click();
    await page.locator('#precap-origen').selectOption('Club PPH');
    assert.ok(await page.locator('[data-precap-conditional="id_pph"]').isVisible());
    await page.locator('#precap-origen').selectOption('Recorrido');
    assert.ok(await page.locator('[data-precap-conditional="id_pph"]').isHidden());
    await page.locator('#precap-tipo_inmueble').selectOption('Casa');
    await page.locator('#precap-categoria').selectOption('Arriendo');
    await page.locator('#precap-contacto').fill('Nueva oportunidad de prueba');
    await page.locator('#precap-celular').fill('3001234567');
    await page.locator('#precap-promocionado_por').selectOption(['Inmmobiliaria']);
    await page.getByRole('button', { name: 'Añadir inmobiliaria', exact: true }).click();
    await page.locator('[data-precap-catalog="inmobiliaria"] input[name="inmobiliaria"]').fill('INMOBILIARIA DE PRUEBA');
    await page.locator('[data-precap-catalog="inmobiliaria"] button[type="submit"]').click();
    await page.locator('#precap-add-inmobiliaria').waitFor({state:'hidden'});
    assert.equal(await page.locator('#precap-competencia').inputValue(), 'Inmobiliaria de prueba');
    assert.ok((await page.locator('#precap-create [data-precap-message]').textContent()).includes('Ya existe'));
    await page.getByRole('button', { name: 'Añadir barrio', exact: true }).click();
    const barrio = page.locator('[data-precap-catalog="barrio"]');
    await barrio.locator('[name="barrio"]').fill('Barrio de prueba nuevo');
    await barrio.locator('[name="latitud"]').fill('6.2');
    await barrio.locator('[name="longitud"]').fill('-75.5');
    await barrio.locator('[name="codigo_postal"]').fill('050021');
    await barrio.locator('button[type="submit"]').click();
    await page.locator('#precap-add-barrio').waitFor({state:'hidden'});
    assert.equal(await page.locator('#precap-barrio').inputValue(), 'Barrio de prueba nuevo');
    await page.locator('#precap-fotos').setInputFiles({name:'evidencia.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jWZkAAAAASUVORK5CYII=', 'base64')});
    fs.mkdirSync('output', {recursive:true});
    await page.screenshot({path:'output/precaptacion-form-desktop.png',fullPage:true});
    const createResponse = page.waitForResponse(response => response.request().method() === 'POST' && response.request().postData().includes('precaptacion_create'));
    await page.locator('#precap-create button[type="submit"]').click();
    const created = await createResponse;
    assert.equal(created.status(), 200, await created.text());
    await page.locator('#precap-create').waitFor({state:'hidden'});
    await page.getByText('Nueva oportunidad de prueba', {exact:true}).first().waitFor({state:'attached'});
    const nonce = await page.locator('body').getAttribute('data-precap-nonce');
    let response = await page.request.post(endpoint, {form:{action:'precaptaciones_actualizar',nonce,id_precaptacion:'2',merece_ticket:'Seguir llamando'}});
    assert.equal(response.status(), 403);
    response = await page.request.post(endpoint, {form:{action:'precaptaciones_filtrar',nonce:'invalid',mode:'mis'}});
    assert.equal(response.status(), 403);
    response = await page.request.post(endpoint, {form:{action:'precaptaciones_filtrar',nonce,mode:'control'}});
    assert.equal(response.status(), 403);
    response = await page.request.post(endpoint, {form:{action:'precaptaciones_actualizar',nonce,id_precaptacion:'1',contacto:'Contacto de prueba',celular:'3001234567',resultado:'Solicita seguimiento',razones:'En proceso',merece_ticket:'Si',id_empleado:'101'}});
    const edited = await response.json();
    assert.equal(response.status(), 200, JSON.stringify(edited));
    assert.ok(edited.data.ticket_modal_html.includes('data-precaptaciones-ticket-form'));
    response = await page.request.post(endpoint, {form:{action:'precaptaciones_crear_ticket',nonce,id_precaptacion:'1',asignado:'101',solicitante:'Contacto de prueba',celular_solicitante:'3001234567',tipo_inmueble:'Casa',destinacion:'Arriendo',asunto:'Prueba',descripcion:'Ticket local de prueba'}});
    const ticket = await response.json();
    assert.equal(response.status(), 200, JSON.stringify(ticket));
    assert.ok(ticket.data.ticket_id);
    response = await page.request.post(endpoint, {form:{action:'precaptaciones_crear_ticket',nonce,id_precaptacion:'1',asignado:'101'}});
    assert.equal((await response.json()).data.ticket_id.toString(), ticket.data.ticket_id.toString());
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button', {name:'Registrar precaptación',exact:true}).click();
    await page.screenshot({path:'output/precaptacion-form-mobile.png',fullPage:true});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'Desbordamiento en móvil');
    assert.deepEqual(errors, []);
    console.log('Precaptación UI: formulario, catálogos, permisos, resultado y ticket OK.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
