const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { chromium } = require(process.argv[2] ? path.join(process.argv[2], 'playwright') : 'playwright');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const endpoint = 'http://127.0.0.1:8770/tests/Fixtures/precaptacion.php';
    await page.route('**/public/precaptacion-api.php', route => route.continue({ url: endpoint }));
    await page.route('**/public/file.php?*', route => route.fulfill({status:200,contentType:'image/png',body:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jWZkAAAAASUVORK5CYII=', 'base64')}));
    await page.goto(endpoint);
    await page.locator('[data-precaptaciones-panel]').waitFor();
    fs.mkdirSync('output', {recursive:true});
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({path:'output/precaptacion-list-desktop.png',fullPage:true});
    assert.equal(await page.locator('.precap-metric').count(), 4);
    assert.ok(!(await page.locator('body').innerText()).match(/\btickets?\b/i));
    assert.ok(await page.locator('#precap-filter-fields').isHidden());
    await page.locator('[data-precap-collapse]').click();
    assert.ok(await page.locator('#precap-filter-fields').isVisible());
    await page.locator('[data-precap-collapse]').click();
    let refresh = page.waitForResponse(response => response.request().postData()?.includes('precaptaciones_filtrar'));
    await page.locator('[data-precap-page-size]').selectOption('25');
    await refresh;
    await page.waitForFunction(() => document.querySelector('[data-precap-page-size]').value === '25');
    const download = page.waitForEvent('download');
    await page.locator('[data-precap-export]').click();
    const csv = fs.readFileSync(await (await download).path(), 'utf8');
    assert.ok(csv.includes('El Poblado'));
    assert.ok(!csv.includes('Registro de otro funcionario'));
    await page.getByRole('button', { name: 'Registrar precaptación', exact: true }).click();
    await page.locator('[data-precap-next]').click();
    assert.ok(await page.locator('[data-precap-step="0"]').isVisible(), 'No debe avanzar con campos obligatorios vacíos');
    await page.locator('#precap-origen').selectOption('Club PPH');
    assert.ok(await page.locator('[data-precap-conditional="id_pph"]').isVisible());
    const pph = page.locator('#precap-id_pph').locator('..');
    await pph.locator('.precap-picker-trigger').click();
    await pph.getByRole('searchbox').fill('Aliado');
    assert.ok((await pph.locator('.precap-picker-option').innerText()).includes('#1'));
    await pph.locator('.precap-picker-option').click();
    await page.locator('#precap-origen').selectOption('Recorrido');
    assert.ok(await page.locator('[data-precap-conditional="id_pph"]').isHidden());
    await page.locator('#precap-tipo_inmueble').selectOption('Casa');
    await page.locator('#precap-categoria').selectOption('Arriendo');
    await page.locator('[data-precap-next]').click();
    assert.ok(await page.locator('[data-precap-step="1"]').isVisible());
    await page.getByRole('button', { name: 'Añadir barrio', exact: true }).click();
    const barrio = page.locator('[data-precap-catalog="barrio"]');
    await barrio.locator('[name="barrio"]').fill('Barrio de prueba nuevo');
    await barrio.locator('[name="latitud"]').fill('6.2');
    await barrio.locator('[name="longitud"]').fill('-75.5');
    await barrio.locator('[name="codigo_postal"]').fill('050021');
    await barrio.locator('button[type="submit"]').click();
    await page.locator('#precap-add-barrio').waitFor({state:'hidden'});
    assert.equal(await page.locator('#precap-barrio').inputValue(), 'Barrio de prueba nuevo');
    await page.locator('[data-precap-next]').click();
    await page.locator('#precap-contacto').fill('Nueva oportunidad de prueba');
    await page.locator('#precap-celular').fill('3001234567');
    const promoter = page.locator('#precap-promocionado_por').locator('..');
    await promoter.locator('.precap-picker-trigger').click();
    await promoter.getByRole('searchbox').fill('mobiliaria');
    await promoter.locator('.precap-picker-option').click();
    assert.deepEqual(await page.locator('#precap-promocionado_por').evaluate(select => Array.from(select.selectedOptions).map(option => option.value)), ['Inmmobiliaria']);
    await page.getByRole('button', { name: 'Añadir inmobiliaria', exact: true }).click();
    await page.locator('[data-precap-catalog="inmobiliaria"] input[name="inmobiliaria"]').fill('INMOBILIARIA DE PRUEBA');
    await page.locator('[data-precap-catalog="inmobiliaria"] button[type="submit"]').click();
    await page.locator('#precap-add-inmobiliaria').waitFor({state:'hidden'});
    assert.equal(await page.locator('#precap-competencia').inputValue(), 'Inmobiliaria de prueba');
    assert.ok((await page.locator('#precap-create [data-precap-message]').textContent()).includes('Ya existe'));
    await page.locator('[data-precap-next]').click();
    assert.ok(await page.locator('[data-precap-step="3"]').isVisible());
    const originalPhoto = Buffer.from(await page.evaluate(() => {
      const canvas = document.createElement('canvas'); canvas.width = 2560; canvas.height = 1600;
      const ctx = canvas.getContext('2d'); const image = ctx.createImageData(canvas.width, canvas.height);
      let seed = 17;
      for (let i = 0; i < image.data.length; i += 4) {
        for (let channel = 0; channel < 3; channel++) { seed ^= seed << 13; seed ^= seed >>> 17; seed ^= seed << 5; image.data[i + channel] = seed & 255; }
        image.data[i + 3] = 255;
      }
      ctx.putImageData(image, 0, 0); return canvas.toDataURL('image/png').split(',')[1];
    }), 'base64');
    await page.locator('#precap-fotos').setInputFiles([
      {name:'fachada.png',mimeType:'image/png',buffer:originalPhoto},
      {name:'evidencia.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jWZkAAAAASUVORK5CYII=', 'base64')},
    ]);
    fs.mkdirSync('output', {recursive:true});
    await page.screenshot({path:'output/precaptacion-form-desktop.png',fullPage:true});
    const createResponse = page.waitForResponse(response => response.request().method() === 'POST' && response.request().postData().includes('precaptacion_create'));
    await page.locator('#precap-create button[type="submit"]').click();
    const created = await createResponse;
    const uploaded = created.request().postDataBuffer();
    assert.ok(uploaded.includes(Buffer.from('filename="fachada.jpg"')));
    assert.ok(uploaded.includes(Buffer.from('filename="evidencia.png"')), 'No debe aumentar una imagen pequeña');
    assert.ok(uploaded.length < originalPhoto.length / 2, 'Las fotos deben comprimirse antes de enviar la solicitud');
    const jpegStart = uploaded.indexOf(Buffer.from([0xff, 0xd8]));
    const jpegEnd = uploaded.indexOf(Buffer.from([0xff, 0xd9]), jpegStart) + 2;
    const dimensions = await page.evaluate(async data => { const image = new Image(); image.src = 'data:image/jpeg;base64,' + data; await image.decode(); return [image.naturalWidth,image.naturalHeight]; }, uploaded.subarray(jpegStart, jpegEnd).toString('base64'));
    assert.deepEqual(dimensions, [1920,1200], 'Debe conservar la proporción y limitar el lado mayor');
    assert.equal(created.status(), 200, await created.text());
    await page.locator('#precap-create').waitFor({state:'hidden'});
    await page.getByText('Nueva oportunidad de prueba', {exact:true}).first().waitFor({state:'attached'});
    const nonce = await page.locator('body').getAttribute('data-precap-nonce');
    let attempt = await page.request.post(endpoint, {form:{action:'precaptaciones_actualizar',nonce,id_precaptacion:'1',resultado:'No contestó',razones:'No contestó',merece_ticket:'Seguir llamando'}});
    assert.equal(attempt.status(), 200);
    refresh = page.waitForResponse(response => response.request().postData()?.includes('precaptaciones_filtrar'));
    await page.locator('[data-precap-contact-filter="no_contesto"]').click();
    await refresh;
    await page.waitForFunction(() => document.querySelector('.precap-contact-badge--no_contesto') !== null);
    assert.ok(/\d{2}\/\d{2}\/\d{4} \d{2}:\d{2}/.test(await page.locator('.precap-dates').innerText()));
    assert.ok(!(await page.locator('.precap-dates').innerText()).includes('No registrada'), 'Debe guardar la fecha de respuesta');
    assert.equal(await page.locator('[data-precaptaciones-row-id]').count(), 1);
    assert.equal(await page.locator('[data-precaptaciones-row-id]').getAttribute('data-precaptaciones-row-id'), '1');
    refresh = page.waitForResponse(response => response.request().postData()?.includes('precaptaciones_filtrar'));
    await page.locator('[data-precap-contact-filter="por_llamar"]').click();
    await refresh;
    await page.waitForFunction(() => document.querySelectorAll('[data-precaptaciones-row-id]').length === 1 && document.querySelector('[data-precaptaciones-row-id]').dataset.precaptacionesRowId !== '1');
    refresh = page.waitForResponse(response => response.request().postData()?.includes('precaptaciones_filtrar'));
    await page.locator('[data-precap-contact-filter=""]').click(); await refresh;
    let response = await page.request.post(endpoint, {form:{action:'precaptaciones_actualizar',nonce,id_precaptacion:'2',merece_ticket:'Seguir llamando'}});
    assert.equal(response.status(), 403);
    response = await page.request.post(endpoint, {form:{action:'precaptaciones_filtrar',nonce:'invalid',mode:'mis'}});
    assert.equal(response.status(), 403);
    response = await page.request.post(endpoint, {form:{action:'precaptaciones_filtrar',nonce,mode:'control'}});
    assert.equal(response.status(), 403);
    response = await page.request.post(endpoint, {form:{action:'precaptaciones_actualizar',nonce,id_precaptacion:'1',contacto:'Contacto de prueba',celular:'3001234567',resultado:'Solicita seguimiento',razones:'En proceso',merece_ticket:'Si',id_empleado:'101'}});
    const edited = await response.json();
    assert.equal(response.status(), 200, JSON.stringify(edited));
    assert.ok(edited.data.ticket_modal_html.includes('data-precaptaciones-ticket-form'));
    response = await page.request.post(endpoint, {form:{action:'precaptaciones_crear_ticket',nonce,id_precaptacion:'1',asignado:'101',solicitante:'Contacto de prueba',celular_solicitante:'3001234567',tipo_inmueble:'Casa',destinacion:'Arriendo',asunto:'Prueba',descripcion:'Ticket local de prueba'}});
    const ticket = await response.json();
    assert.equal(response.status(), 200, JSON.stringify(ticket));
    assert.ok(ticket.data.ticket_id);
    response = await page.request.post(endpoint, {form:{action:'precaptaciones_crear_ticket',nonce,id_precaptacion:'1',asignado:'101'}});
    assert.equal((await response.json()).data.ticket_id.toString(), ticket.data.ticket_id.toString());
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button', {name:'Registrar precaptación',exact:true}).click();
    await page.screenshot({path:'output/precaptacion-form-mobile.png',fullPage:true});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'Desbordamiento en móvil');
    await page.locator('#precap-create [data-precap-close]').first().click();
    await page.screenshot({path:'output/precaptacion-list-mobile.png',fullPage:true});
    const admin = await browser.newPage({viewport:{width:1440,height:1000}});
    await admin.route('**/public/precaptacion-api.php', route => route.continue({url:endpoint}));
    await admin.goto(endpoint + '?admin=1&normalize=1');
    await admin.evaluate(() => document.fonts.ready);
    await admin.screenshot({path:'output/precaptacion-admin-desktop.png',fullPage:true});
    assert.equal(await admin.locator('h1').innerText(), 'Precaptaciones');
    assert.ok(!(await admin.locator('body').innerText()).match(/\btickets?\b/i));
    for (const kind of ['promocionado','competencia']) {
      const button = admin.locator('[data-precaptaciones-normalizar-' + kind + ']');
      assert.equal(await button.getAttribute('data-count'), '1');
      const action = kind === 'promocionado' ? 'precaptaciones_normalizar_promocionado_por' : 'precaptaciones_normalizar_competencia';
      const result = admin.waitForResponse(response => response.request().postData()?.includes(action));
      await button.click();
      await admin.locator('[data-precap-notice-confirm]').click();
      const normalized = await (await result).json();
      assert.equal(normalized.success, true, JSON.stringify(normalized));
      assert.equal(normalized.data.updated, 1);
      assert.equal(normalized.data.remaining, 0);
      await admin.waitForFunction(kind => document.querySelector('[data-precaptaciones-normalizar-' + kind + ']').dataset.count === '0', kind);
      assert.ok(await button.isDisabled());
      assert.ok((await button.innerText()).includes('Normalizar'));
    }
    await admin.goto(endpoint + '?admin=1');
    assert.equal(await admin.locator('[data-precaptaciones-normalizar-competencia]').getAttribute('data-count'), '0');
    assert.equal(await admin.locator('[data-precaptaciones-normalizar-promocionado]').getAttribute('data-count'), '0');
    assert.ok((await admin.locator('.precap-dates').first().innerText()).includes('No registrada'), 'Normalizar no debe inventar una respuesta');
    let nativeDialogs = 0;
    admin.on('dialog', async dialog => { nativeDialogs++; await dialog.dismiss(); });
    await admin.locator('[data-precaptaciones-duplicada]').first().click();
    await admin.locator('#precap-notice').waitFor({state:'visible'});
    await admin.screenshot({path:'output/precaptacion-confirmation-desktop.png'});
    await admin.locator('[data-precap-notice-cancel]').click();
    assert.equal(nativeDialogs, 0);
    await admin.locator('[data-precaptaciones-modal-open]').first().click();
    await admin.locator('.precap-detail-body').first().waitFor({state:'visible'});
    await admin.screenshot({path:'output/precaptacion-detail-desktop.png'});
    await admin.locator('.precaptaciones-precap-modal__close').first().click();
    await admin.setViewportSize({width:390,height:844});
    assert.equal(await admin.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'Desbordamiento del panel administrativo en móvil');
    await admin.screenshot({path:'output/precaptacion-admin-mobile.png',fullPage:true});
    assert.deepEqual(errors, []);
    console.log('Precaptación UI: diseño responsive, filtros, exportación, formulario, catálogos, permisos y tarea OK.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
