// Ejecutar después de preview-commercial-notifications.php y servir el repo en 127.0.0.1:8769.
const path = require('path');
const { chromium } = require(process.argv[2] ? path.join(process.argv[2], 'playwright') : 'playwright');
let browser;

(async () => {
  browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  let recipientRequests = 0, sendRequests = 0;
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', async dialog => { errors.push('El módulo abrió una alerta nativa'); await dialog.dismiss(); });
  page.on('request', request => { if (request.url().includes('notifications-api.php') && request.postData()?.includes('commercial_notifications_recipients')) recipientRequests++; });
  page.on('request', request => { if (request.url().includes('notifications-api.php') && request.postData()?.includes('commercial_notifications_send')) sendRequests++; });
  await page.goto('http://127.0.0.1:8769/output/notifications-preview.html');
  if (recipientRequests !== 0 || await page.locator('[data-notif-modal]').isVisible()) throw new Error('Se carga un actor o editor sin abrirlo');
  if ((await page.locator('[data-notif-type]').count()) !== 6 || (await page.locator('[data-notif-import]').count()) !== 0) throw new Error('Categorías o selección SIMI incorrectas');
  await page.locator('[data-notif-type="propietarios_no_activos"]').click();
  await page.locator('[data-notif-recipient][value="11"]').waitFor();
  if (recipientRequests !== 1) throw new Error('Abrir un actor genera consultas duplicadas');
  if ((await page.locator('[data-notif-recipient][value="10"]').count()) !== 0) throw new Error('Los propietarios activos aparecen en no activos');
  await page.locator('[data-notif-type="arrendatarios_no_activos"]').click();
  await page.locator('[data-notif-recipient][value="21"]').waitFor();
  await page.locator('[data-notif-type="arrendatarios_activos"]').click();
  await page.locator('[data-notif-recipient][value="20"]').waitFor();
  if ((await page.locator('[data-notif-recipient][value="21"]').count()) !== 0) throw new Error('Los arrendatarios no activos aparecen en activos');
  if (!(await page.locator('[data-notif-single-channel="all"][data-id="20"]').isDisabled())) throw new Error('Un contacto sin datos permite envío individual');
  await page.locator('[data-notif-type="propietarios_activos"]').click();
  await page.locator('[data-notif-recipient][value="10"]').waitFor();
  if (!(await page.locator('[data-notif-single-channel="email"][data-id="14"]').isDisabled())) throw new Error('Un contacto sin correo permite Email');
  if (!(await page.locator('[data-notif-single-channel="whatsapp"][data-id="15"]').isDisabled()) || !(await page.locator('[data-notif-single-channel="sms"][data-id="15"]').isDisabled())) throw new Error('Un contacto sin celular permite WhatsApp/SMS');
  await page.locator('[data-notif-recipient][value="15"]').check();
  if (!(await page.locator('[data-notif-open-channel="whatsapp"]').isDisabled()) || await page.locator('[data-notif-open-channel="email"]').isDisabled()) throw new Error('La selección no respeta los datos disponibles');
  await page.locator('[data-notif-single-channel="all"][data-id="15"]').click();
  if ((await page.locator('[data-notif-compose] [name="channels[]"]:checked').count()) !== 1 || !(await page.locator('[data-notif-compose] [value="sms"]').isDisabled())) throw new Error('El popup permite canales sin destino');
  await page.locator('[data-notif-close]').click();
  await page.locator('[data-notif-recipient][value="15"]').uncheck();
  await page.locator('[data-notif-recipient][value="10"]').check();
  await page.locator('[data-notif-open-channel="whatsapp"]').click();
  await page.locator('#notif-message').fill('Tu asesoría está agendada para mañana a las 10:00 a. m.');
  const preview = await page.locator('[data-notif-preview]').textContent();
  if (!preview.includes('Propietario 10') || !preview.includes('Atentamente,\nAna Pérez') || !preview.includes('3001234567')) throw new Error('La vista previa perdió el saludo o firma');
  await page.screenshot({ path: 'output/notifications-desktop.png', fullPage: true });
  await page.locator('[data-notif-close]').click();
  // El botón individual preserva la selección masiva y abre el canal elegido.
  await page.locator('[data-notif-single-channel="email"][data-id="10"]').click();
  const mail = page.frameLocator('[data-notif-email-preview]');
  await mail.locator('img').waitFor();
  if (!(await mail.locator('img').getAttribute('src')).includes('banner-sitio-web') || !(await mail.locator('body').textContent()).includes('Propietario 10') || !(await mail.locator('body').textContent()).includes('Atentamente,')) throw new Error('El correo pierde banner, saludo o cierre');
  await page.screenshot({ path: 'output/notifications-email.png', fullPage: true });
  await page.locator('[data-notif-close]').click();
  if (!(await page.locator('[data-notif-recipient][value="10"]').isChecked())) throw new Error('El envío individual altera la selección masiva');
  await page.locator('[data-notif-open-channel="all"]').click();
  if ((await page.locator('[data-notif-compose] [name="channels[]"]:checked').count()) !== 3) throw new Error('Todos los canales no activa los tres medios');
  await page.locator('[data-notif-preview-channel="sms"]').click();
  if (!(await page.locator('[data-notif-preview]').textContent()).startsWith('SKC SuCasa Inmobiliaria ')) throw new Error('La vista SMS no contiene el prefijo');
  await page.locator('[data-notif-close]').click();
  await page.locator('[data-notif-single-channel="sms"][data-id="10"]').click();
  const smsRemaining = await page.locator('[data-commercial-notifications]').evaluate(node => 160 - JSON.parse(node.dataset.notificationConfig).sms.prefix.length);
  await page.locator('#notif-message').fill('A'.repeat(smsRemaining + 1));
  if (!(await page.locator('[data-notif-send]').isDisabled()) || !(await page.locator('[data-notif-sms-length]').textContent()).includes('161/160')) throw new Error('SMS excedido no se bloquea');
  await page.locator('#notif-message').fill('A'.repeat(smsRemaining));
  if (await page.locator('[data-notif-send]').isDisabled()) throw new Error('SMS de 160 caracteres está bloqueado');
  await page.locator('#notif-message').fill('A'.repeat(60) + '😀');
  if (!(await page.locator('[data-notif-sms-length]').textContent()).includes('2 segmentos')) throw new Error('SMS no informa segmentos Unicode');
  await page.locator('[data-notif-close]').click();
  await page.locator('[data-notif-select-all]').click();
  await page.locator('[data-notif-recipient][value="15"]').uncheck();
  if ((await page.locator('[data-notif-selected]').textContent()) !== '2 seleccionados' || !(await page.locator('[data-notif-recipient][value="10"]').isChecked())) throw new Error('Deseleccionar un resultado cancela la selección total');
  await page.locator('[data-notif-clear]').click();
  await page.locator('[data-notif-recipient][value="10"]').check();
  await page.locator('[data-notif-open-channel="whatsapp"]').click();
  await page.locator('#notif-message').fill('Tu asesoría está agendada para mañana a las 10:00 a. m.');
  await page.locator('#notif-template').selectOption('scm_marketing_generica_documento_v1');
  if (!(await page.locator('[data-notif-media-fields]').isVisible())) throw new Error('El encabezado PDF no solicita archivo');
  await page.locator('#notif-template').selectOption('scm_marketing_generica_texto_v1');
  if (await page.locator('[data-notif-media-fields]').isVisible()) throw new Error('Texto muestra un archivo innecesario');
  let releaseSend;
  const holdSend = route => {
    if (!route.request().postData()?.includes('commercial_notifications_send')) return route.continue();
    return new Promise(resolve => { releaseSend = resolve; }).then(() => route.continue());
  };
  await page.route('**/tests/Fixtures/notifications-api.php', holdSend);
  await page.locator('[data-notif-send]').click();
  await page.locator('[data-notif-confirm-modal]').waitFor();
  if (!(await page.locator('[data-notif-confirm-channels]').textContent()).includes('WhatsApp') || sendRequests !== 0) throw new Error('La confirmación omite canales o envía sin aprobación');
  await page.screenshot({ path: 'output/notifications-confirm.png', fullPage: true });
  await page.locator('[data-notif-confirm-cancel]').click();
  if (sendRequests !== 0 || !(await page.locator('[data-notif-modal]').isVisible())) throw new Error('Cancelar envía mensajes o pierde el editor');
  await page.locator('[data-notif-send]').click();
  await page.keyboard.press('Escape');
  if (sendRequests !== 0 || await page.locator('[data-notif-confirm-modal]').isVisible()) throw new Error('Escape no cancela la confirmación');
  await page.locator('[data-notif-send]').click();
  await page.locator('[data-notif-confirm-send]').click();
  await page.locator('[data-notif-confirm-progress]').waitFor();
  if (!(await page.locator('[data-notif-confirm-send]').isDisabled()) || !(await page.locator('[data-notif-confirm-cancel]').isDisabled())) throw new Error('Se puede confirmar de nuevo durante el encolado');
  await page.keyboard.press('Escape');
  if (!(await page.locator('[data-notif-confirm-modal]').isVisible())) throw new Error('Se cierra la confirmación durante el encolado');
  if (!releaseSend) throw new Error('No se inició la solicitud de encolado');
  releaseSend();
  await page.locator('[data-notif-feedback]').filter({ hasText: '1 notificaciones en cola' }).waitFor();
  await page.unroute('**/tests/Fixtures/notifications-api.php', holdSend);
  await page.locator('[data-notif-result-modal]').waitFor();
  if ((await page.locator('[data-notif-result-count="queued"]').textContent()) !== '1' || !(await page.locator('[data-notif-result-title]').textContent()).includes('Mensajes encolados') || sendRequests !== 1) throw new Error('Falta el resultado del encolado o hay un envío duplicado');
  await page.screenshot({ path: 'output/notifications-result.png', fullPage: true });
  await page.locator('[data-notif-result-close]').click();
  if (!(await page.locator('[data-notif-single-channel="email"][data-id="14"]').isDisabled())) throw new Error('Un envío vuelve a habilitar canales inválidos');
  await page.locator('[data-notif-type="club_pph"]').click();
  await page.locator('[data-notif-recipients]').getByText('Club PPH 40', { exact: true }).waitFor();
  if (await page.locator('[data-notif-contract-filters]').isVisible()) throw new Error('Club PPH muestra filtros de contrato');
  await page.locator('[data-notif-view="queue"]').click();
  await page.locator('[data-notif-queue-rows]').getByText('Todavía no hay notificaciones en este estado.').waitFor();
  // Comprobar los endpoints reales con base aislada: permisos, CSRF y alcance en envío.
  const call = async extra => page.request.post('http://127.0.0.1:8769/tests/Fixtures/notifications-api.php', { form: { action: 'commercial_notifications_recipients', nonce: 'fixture', type: 'propietarios_activos', ...extra } });
  const lazyResponse = await call({});
  if ('stats' in (await lazyResponse.json()).data) throw new Error('La búsqueda recalcula los seis actores');
  if ((await call({ restricted: '1' })).status() !== 403) throw new Error('API sin control de visibilidad');
  if ((await call({ nonce: 'incorrecto' })).status() !== 403) throw new Error('API sin CSRF');
  const outside = await call({ action: 'commercial_notifications_send', 'ids[]': '13', 'channels[]': 'whatsapp', request_id: 'a'.repeat(32), message: 'Mensaje de prueba', whatsapp_template: 'scm_marketing_generica_texto_v1' });
  if (outside.status() !== 422) throw new Error('API permite destinatario ajeno');
  const smsRejected = await call({ action: 'commercial_notifications_send', 'ids[]': '10', 'channels[]': 'sms', request_id: 'd'.repeat(32), message: 'A'.repeat(smsRemaining + 1) });
  if (smsRejected.status() !== 422) throw new Error('API acepta SMS de más de 160 caracteres');
  const excluding = await call({ action: 'commercial_notifications_send', all_filtered: '1', 'exclude_ids[]': '10', 'channels[]': 'whatsapp', request_id: 'b'.repeat(32), message: 'Mensaje de prueba', whatsapp_template: 'scm_marketing_generica_texto_v1' });
  const excludingResult = await excluding.json();
  if (excluding.status() !== 200 || excludingResult.data.selected !== 2 || excludingResult.data.queued !== 0 || excludingResult.data.filtered !== 2) throw new Error('API perdió exclusiones o preferencias en selección total');
  const upload = async content => page.request.post('http://127.0.0.1:8769/tests/Fixtures/notifications-api.php', { multipart: {
    action: 'commercial_notifications_send', nonce: 'fixture', type: 'propietarios_activos', 'ids[]': '10', 'channels[]': 'whatsapp', request_id: 'c'.repeat(32), message: 'Mensaje con PDF', whatsapp_template: 'scm_marketing_generica_documento_v1', media_type: 'document',
    media: { name: 'prueba.pdf', mimeType: 'application/pdf', buffer: Buffer.from(content) }
  } });
  if ((await upload('Esto no es un PDF')).status() !== 422) throw new Error('Se acepta un archivo con MIME incorrecto');
  const pdfResult = await upload('%PDF-1.4\n1 0 obj\n<< /Type /Catalog >>\nendobj\n%%EOF');
  if (pdfResult.status() !== 200 || (await pdfResult.json()).data.queued !== 1) throw new Error('No se puede guardar y encolar un encabezado PDF');
  await page.locator('[data-notif-view="recipients"]').click();
  await page.locator('[data-notif-type="propietarios_activos"]').click();
  await page.locator('[data-notif-recipient][value="10"]').waitFor();
  const beforeCache = recipientRequests;
  await page.locator('[data-notif-type="propietarios_activos"]').click();
  await page.locator('[data-notif-recipient][value="10"]').waitFor();
  if (recipientRequests !== beforeCache) throw new Error('Volver a un actor no reutiliza la consulta');
  await page.locator('[data-notif-recipient-refresh]').click();
  await page.locator('[data-notif-recipient][value="10"]').waitFor();
  if (recipientRequests !== beforeCache + 1) throw new Error('Actualizar no renueva los contactos');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'output/notifications-mobile.png', fullPage: true });
  const panelOverflow = await page.locator('[data-commercial-notifications]').evaluate(node => node.scrollWidth > node.clientWidth);
  if (panelOverflow) throw new Error('El módulo desborda en móvil');
  const pageOverflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  if (pageOverflow) throw new Error('La navegación desborda en móvil');
  await page.locator('[data-notif-single-channel="email"][data-id="10"]').click();
  await page.screenshot({ path: 'output/notifications-mobile-email.png', fullPage: true });
  if (await page.locator('[data-notif-modal]').evaluate(node => node.scrollWidth > node.clientWidth)) throw new Error('El popup desborda en móvil');
  await page.keyboard.press('Escape');
  if (await page.locator('[data-notif-modal]').isVisible()) throw new Error('Escape no cierra el editor');
  // Respuestas controladas para cubrir encolado parcial, omisiones y error del servidor.
  let simulatedResult;
  await page.route('**/tests/Fixtures/notifications-api.php', route => {
    if (!route.request().postData()?.includes('commercial_notifications_send')) return route.continue();
    return route.fulfill({ status: simulatedResult.success ? 200 : 500, contentType: 'application/json', body: JSON.stringify(simulatedResult) });
  });
  for (const scenario of [
    { success: true, data: { queued: 1, failed: 1, invalid: 2, filtered: 3, message: 'Resultado parcial' }, title: 'Encolado parcial' },
    { success: true, data: { queued: 0, failed: 0, invalid: 1, filtered: 0, message: 'Sin destinos' }, title: 'No se encolaron mensajes' },
    { success: false, data: { message: 'Error de prueba del servidor' }, title: 'No se pudo confirmar el encolado' }
  ]) {
    simulatedResult = scenario;
    await page.locator('[data-notif-single-channel="whatsapp"][data-id="10"]').click();
    await page.locator('#notif-message').fill('Mensaje de prueba');
    await page.locator('[data-notif-send]').click();
    await page.locator('[data-notif-confirm-send]').click();
    await page.locator('[data-notif-result-modal]').waitFor();
    if ((await page.locator('[data-notif-result-title]').textContent()) !== scenario.title) throw new Error('El popup no distingue el resultado del envío');
    if (await page.locator('[data-notif-result-modal]').evaluate(node => node.scrollWidth > node.clientWidth)) throw new Error('El resultado desborda en móvil');
    if (scenario.success && (await page.locator('[data-notif-result-count="invalid"]').textContent()) !== String(scenario.data.invalid)) throw new Error('El resultado omite contactos sin datos');
    if (!scenario.success && !(await page.locator('[data-notif-result-description]').textContent()).includes(scenario.data.message)) throw new Error('No se muestra el error del servidor');
    await page.screenshot({ path: 'output/notifications-result-mobile.png', fullPage: true });
    await page.locator('[data-notif-result-close]').click();
    await page.locator('[data-notif-close]').click();
  }
  // La acción del resultado abre la cola y cierra los diálogos.
  simulatedResult = { success: true, data: { queued: 1, failed: 0, invalid: 0, filtered: 0, message: '1 notificaciones en cola' } };
  await page.locator('[data-notif-single-channel="whatsapp"][data-id="10"]').click();
  await page.locator('[data-notif-send]').click();
  await page.locator('[data-notif-confirm-send]').click();
  await page.locator('[data-notif-result-queue]').click();
  await page.locator('[data-notif-queue-rows]').getByText('Todavía no hay notificaciones en este estado.').waitFor();
  if (await page.locator('[data-notif-result-modal]').isVisible() || await page.locator('[data-notif-modal]').isVisible()) throw new Error('Ver cola deja un popup abierto');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('UI: confirmación sin alertas, cancelación, resultados completos/parciales/error, acceso a cola, canales, SMS, permisos y responsive: OK');
  await browser.close();
})().catch(async error => { console.error(error); await browser?.close(); process.exitCode = 1; });
