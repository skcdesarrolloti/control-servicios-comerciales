// Requiere generar la vista --audit --admin y servir el repositorio en 127.0.0.1:8769.
const path = require('path');
const assert = require('node:assert/strict');
const { chromium } = require(process.argv[2] ? path.join(process.argv[2], 'playwright') : 'playwright');
let browser;
(async () => {
  browser = await chromium.launch({ headless: true, channel: 'msedge' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = 'http://127.0.0.1:8769';
  const api = (action, extra = {}, admin = false) => page.request.post(base + '/tests/Fixtures/notifications-api.php?audit=' + (admin ? 'admin' : 'user'), { form: { action, nonce: 'fixture', ...extra } });
  for (const action of ['commercial_actor_detail', 'commercial_actor_preview', 'commercial_actor_save']) {
    assert.equal((await api(action, { id: '10', type: 'propietarios_activos' })).status(), 403);
    assert.equal((await api(action, { nonce: 'bad' }, true)).status(), 403);
  }
  assert.equal((await api('commercial_actor_detail', { type: 'invalid', id: '10' }, true)).status(), 404);
  assert.equal((await api('commercial_actor_save', { token: 'inventado' }, true)).status(), 409);
  await page.goto(base + '/output/notifications-audit-user.html');
  await page.locator('[data-notif-type="propietarios_activos"]').click();
  await page.locator('[data-notif-recipient][value="10"]').waitFor();
  assert.equal(await page.locator('[data-notif-edit-actor]').count(), 0);
  await page.goto(base + '/output/notifications-audit-admin' + (process.argv.includes('--shell') ? '-shell' : '') + '.html');
  if (process.argv.includes('--shell')) assert.match(await page.locator('script[src*="commercial-notifications.js"]').getAttribute('src'), /\?v=[a-f0-9]{64}$/);
  await page.locator('[data-notif-type="propietarios_activos"]').click();
  await page.locator('[data-notif-edit-actor="10"]').click();
  const modal = page.locator('[data-notif-actor-modal]');
  const form = page.locator('[data-notif-actor-form]');
  await form.waitFor({ state: 'visible' });
  const save = page.locator('[data-notif-actor-save]');
  const confirm = page.locator('[data-notif-actor-confirm]');
  assert.equal(await save.isVisible(), false);
  assert.equal(await save.isDisabled(), true);
  assert.equal(await form.locator('[name="nombre"]').inputValue(), 'Propietario 10');
  assert.equal(await form.locator('[name="documento"]').inputValue(), '123456');
  const country = form.locator('[data-notif-actor-country]');
  assert.equal(await country.locator('option:checked').innerText(), 'Colombia (+57)');
  assert.equal(await country.inputValue(), '57', 'Abrir el selector conserva el indicativo original');
  assert.match(await country.innerText(), /España \(\+34\)/);
  assert.match(await country.innerText(), /Canadá \/ Estados Unidos \(\+1\)/);
  await country.selectOption('+34');
  assert.equal(await country.locator('option:checked').innerText(), 'España (+34)');
  await country.selectOption({label: 'Colombia (+57)'});
  assert.equal(await form.locator('[name="groups[]"]').count(), 4);
  assert.equal(await form.locator('[data-notif-actor-record]').count(), 5);
  const related = form.locator('[data-notif-actor-related]');
  const relatedGroups = related.locator('[data-notif-actor-related-group]');
  assert.equal(await relatedGroups.count(), 4);
  assert.equal(await related.locator('details[open]').count(), 0);
  const propertySummary = related.locator('details[data-group="inmuebles"] summary');
  await propertySummary.focus(); await page.keyboard.press('Enter');
  assert.equal(await related.locator('[value="inmuebles:2"]').isVisible(), true);
  await page.keyboard.press('Enter');
  assert.equal(await related.locator('[value="inmuebles:2"]').isVisible(), false);
  await modal.screenshot({path: 'output/actor-editor-country-accordions.png'});
  for (const group of await relatedGroups.all()) await group.locator('summary').click();
  for (const text of ['Inmueble #2', 'SIMI-100', 'Mandato #1', 'C-2', 'C-7', 'Cierre #1', 'Cerrado', 'Propietario original']) {
    assert.ok((await related.innerText()).includes(text), 'Falta identificación inicial: ' + text);
  }
  // El botón siempre abre la comparación, incluso antes de modificar los datos.
  await page.locator('[data-notif-actor-review]').click();
  await page.locator('[data-notif-actor-review-panel]').waitFor({ state: 'visible' });
  assert.equal(await page.locator('[data-notif-actor-target]').count(), 6);
  assert.equal(await page.locator('[data-notif-actor-comparison-group]').count(), 4);
  assert.equal(await page.locator('[data-notif-actor-comparison-group][open]').count(), 0);
  assert.match(await page.locator('[data-notif-actor-changes] > section').innerText(), /Colombia \(\+57\)/);
  assert.match(await page.locator('[data-notif-actor-feedback]').innerText(), /No modificaste los datos/);
  assert.equal(await save.isVisible(), true);
  assert.equal(await save.isDisabled(), true);
  await confirm.check();
  assert.equal(await save.isDisabled(), true, 'No debe guardar sin cambios aunque se marque confirmar');
  await page.locator('[data-notif-actor-back]').click();
  assert.equal(await save.isVisible(), false);
  await form.locator('[name="correo"]').fill('correo-invalido');
  await page.locator('[data-notif-actor-review]').click();
  assert.match(await page.locator('[data-notif-actor-feedback]').innerText(), /Revisa los campos señalados/);
  assert.equal(await form.isVisible(), true);
  assert.equal(await save.isDisabled(), true);
  await form.locator('[name="correo"]').fill('persona10@example.test');
  await form.locator('[name="documento"]').fill('654321');
  await page.locator('[data-notif-actor-review]').click();
  await page.locator('[data-notif-actor-feedback]').filter({ hasText: 'Ya existe otro actor' }).waitFor();
  assert.equal(await form.isVisible(), true);
  assert.equal(await save.isDisabled(), true);
  await form.locator('[name="documento"]').fill('123456');
  await form.locator('[data-notif-actor-group][value="arrendamientos"]').uncheck();
  assert.equal(await related.locator('details[data-group="arrendamientos"]').isVisible(), false);
  assert.equal(await form.locator('[data-notif-actor-record][data-group="arrendamientos"]:checked').count(), 0);
  await form.locator('[data-notif-actor-group][value="arrendamientos"]').check();
  assert.equal(await related.locator('details[data-group="arrendamientos"]').isVisible(), true);
  assert.equal(await related.locator('details[data-group="arrendamientos"]').getAttribute('open') !== null, true);
  await form.locator('[data-notif-actor-record][value="arrendamientos:2"]').uncheck();
  assert.equal(await form.locator('[data-notif-actor-group][value="arrendamientos"]').evaluate(node => node.indeterminate), true);
  assert.match(await form.locator('[data-notif-actor-related-summary]').innerText(), /4 de 5/);
  await page.setViewportSize({ width: 390, height: 844 });
  await relatedGroups.evaluateAll(nodes => nodes.forEach(node => { node.open = false; }));
  assert.equal(await modal.evaluate(node => node.scrollWidth > node.clientWidth), false, 'La lista inicial desborda el móvil');
  await related.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'output/actor-editor-records-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await form.locator('[name="nombre"]').fill('Nombre corregido');
  await form.locator('[name="documento"]').fill('123456-7');
  await form.locator('[name="correo"]').fill('corregido@example.test');
  await form.locator('[name="celular"]').fill('3001112233');
  await country.selectOption('+34');
  await page.screenshot({ path: 'output/actor-editor-form.png', fullPage: true });
  await page.locator('[data-notif-actor-review]').click();
  await page.locator('[data-notif-actor-review-panel]').waitFor({ state: 'visible' });
  assert.equal(await save.isVisible(), true);
  assert.equal(await save.isDisabled(), true, 'Requiere confirmación explícita');
  assert.equal(await page.locator('[data-notif-actor-comparison-title]').evaluate(node => document.activeElement === node), true);
  assert.equal(await page.locator('[data-notif-actor-target]').count(), 5);
  assert.equal(await page.locator('[data-notif-actor-target][value="arrendamientos:2"]').count(), 0);
  assert.equal(await page.locator('[data-notif-actor-target][value="actor:10"]').isDisabled(), true);
  const mainComparison = page.locator('[data-notif-actor-changes] > section');
  assert.match(await mainComparison.innerText(), /Colombia \(\+57\)/);
  assert.match(await mainComparison.innerText(), /España \(\+34\)/);
  for (const group of await page.locator('[data-notif-actor-comparison-group]').all()) await group.locator('summary').click();
  assert.match(await page.locator('[data-notif-actor-changes]').innerText(), /Nombre corregido/);
  assert.match(await page.locator('[data-notif-actor-changes]').innerText(), /Mandato #1/);
  assert.match(await page.locator('[data-notif-actor-changes]').innerText(), /Cerrado/);
  assert.match(await page.locator('[data-notif-actor-changes]').innerText(), /Valor actual/);
  assert.match(await page.locator('[data-notif-actor-changes]').innerText(), /Así quedará/);
  const mandate = page.locator('[data-notif-actor-changes] section').filter({ hasText: 'Mandato #1' });
  assert.match(await mandate.innerText(), /Propietario original/);
  assert.match(await mandate.innerText(), /Nombre corregido/);
  assert.equal((await page.locator('[data-notif-actor-changes]').innerText()).includes('titular 2'), false);
  await page.screenshot({ path: 'output/actor-editor-preview.png', fullPage: true });
  await page.locator('[data-notif-actor-back]').click();
  await form.waitFor({ state: 'visible' });
  assert.equal(await form.locator('[data-notif-actor-record][value="arrendamientos:2"]').isChecked(), false);
  await related.locator('details[data-group="arrendamientos"] summary').click();
  await form.locator('[data-notif-actor-record][value="arrendamientos:2"]').check();
  await form.locator('[name="nombre"]').fill('Nombre final');
  await page.locator('[data-notif-actor-review]').click();
  await page.locator('[data-notif-actor-review-panel]').waitFor({ state: 'visible' });
  await page.locator('[data-notif-actor-comparison-group][data-group="arrendamientos"] summary').click();
  await page.locator('[data-notif-actor-target][value="arrendamientos:2"]').uncheck();
  await confirm.check();
  assert.equal(await save.isEnabled(), true);
  await page.locator('[data-notif-actor-target][value="arrendamientos:7"]').uncheck();
  assert.equal(await confirm.isChecked(), false, 'Cambiar la selección debe pedir una nueva confirmación');
  assert.equal(await save.isDisabled(), true);
  await page.locator('[data-notif-actor-target][value="arrendamientos:7"]').check();
  await confirm.check();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await modal.evaluate(node => node.scrollWidth > node.clientWidth), false, 'El editor desborda el móvil');
  await modal.evaluate(node => { node.scrollTop = 0; });
  const saveBox = await save.boundingBox(), modalBox = await modal.boundingBox();
  assert.ok(saveBox.y >= modalBox.y && saveBox.y + saveBox.height <= modalBox.y + modalBox.height, 'Guardar cambios debe permanecer visible al inicio de la comparación');
  await page.screenshot({ path: 'output/actor-editor-preview-mobile.png', fullPage: true });
  const saved = page.waitForResponse(response => response.url().includes('notifications-api.php') && response.request().postData()?.includes('commercial_actor_save'));
  await page.locator('[data-notif-actor-save]').click();
  const result = await (await saved).json();
  assert.equal(result.success, true);
  assert.equal(result.data.updated, 5);
  await page.locator('[data-notif-feedback]').filter({ hasText: 'Datos guardados en el actor y 4 registros relacionados.' }).waitFor();
  assert.equal(await modal.isVisible(), false);
  for (const [type, id] of [['arrendatarios_activos', '22'], ['copropiedades', '32'], ['club_pph', '40']]) {
    await page.locator('[data-notif-type="' + type + '"]').click();
    await page.locator('[data-notif-edit-actor="' + id + '"]').click();
    await form.waitFor({ state: 'visible' });
    assert.equal(await form.locator('[name="nombre"]').inputValue() !== '', true);
    assert.ok(await form.locator('[data-notif-actor-record]').count() > 0);
    await page.locator('[data-notif-actor-close]').click();
  }
  await page.locator('[data-notif-type="copropiedades"]').click();
  await page.locator('[data-notif-edit-actor="33"]').click();
  await form.waitFor({ state: 'visible' });
  assert.match(await related.innerText(), /No se encontraron registros relacionados/);
  assert.equal(await form.locator('[data-notif-actor-group]:checked').count(), 0);
  await form.locator('[name="nombre"]').fill('Solo principal');
  await page.locator('[data-notif-actor-review]').click();
  await page.locator('[data-notif-actor-review-panel]').waitFor({ state: 'visible' });
  assert.equal(await page.locator('[data-notif-actor-target]').count(), 1);
  assert.deepEqual(errors, []);
  console.log('Editor de actores: país e indicativo, acordeones y teclado, comparación, confirmación, guardado, permisos, selección, cuatro tipos y móvil: OK');
  await browser.close();
})().catch(async error => { console.error(error); if (browser) await browser.close(); process.exit(1); });
